<h2 class="h4 mb-4">Jagorar OpenWrt / Compatible Router</h2>

<div class="alert alert-warning">
Ana shirya HotFii OpenWrt automated provisioning.
Kada a yi amfani da wannan jagora wajen flashing router da ba a tabbatar yana goyon bayan OpenWrt ba.
</div>

<div class="guide-step">
<h3 class="h5">1. Mene ne OpenWrt-Compatible Router?</h3>

<p>
OpenWrt firmware ne, ba kamfanin kera router ba.
Wasu routers na GL.iNet, TP-Link, D-Link, Linksys,
Netgear, Xiaomi, Cudy da sauransu suna iya goyon bayan OpenWrt.
</p>

<p>
Support yana dogara da ainihin
<strong>model da hardware revision</strong>.
</p>
</div>

<div class="guide-step">
<h3 class="h5">2. Tabbatar da compatibility kafin komai</h3>

<p>
Kafin a cire factory firmware, a tabbatar exact model
da hardware revision suna goyon bayan OpenWrt.
</p>

<div class="alert alert-danger">
Kada a saka firmware na wani model ko hardware revision daban.
Hakan na iya lalata router.
</div>
</div>

<div class="guide-step">
<h3 class="h5">3. Factory firmware da OpenWrt</h3>

<p>
D-Link, TP-Link ko wani router da yake amfani da original
manufacturer firmware ba zai yi amfani da HotFii OpenWrt setup kai tsaye ba.
</p>

<pre><code>Compatible router
      ↓
Install OpenWrt
      ↓
Tabbatar OpenWrt yana aiki
      ↓
Create OpenWrt device a HotFii
      ↓
Run HotFii provisioning</code></pre>
</div>

<div class="guide-step">
<h3 class="h5">4. Tabbatar da Internet</h3>

<p>
Bayan OpenWrt ya shiga, tabbatar WAN/Internet yana aiki kafin HotFii provisioning.
</p>
</div>

<div class="guide-step">
<h3 class="h5">5. HotFii Provisioning</h3>

<p>
Da zarar mun kunna OpenWrt adapter,
HotFii zai samar da setup na musamman ga wannan router.
</p>

<p>Manufar setup ita ce ta saita:</p>

<ul>
<li>Secure management connection</li>
<li>RADIUS authentication</li>
<li>RADIUS accounting</li>
<li>Captive portal</li>
<li>Voucher authentication</li>
<li>Time/data limits</li>
<li>Session monitoring</li>
<li>Remote disconnect</li>
<li>Heartbeat monitoring</li>
</ul>
</div>

<div class="guide-step" id="troubleshooting">
<h3 class="h5">Muhimman Gargadi</h3>

<ul>
<li>Kada a flash OpenWrt sai an tabbatar da exact hardware support.</li>
<li>A yi backup kafin canza firmware.</li>
<li>Kada a yi amfani da HotFii credentials na wani router.</li>
<li>Hanyar installation tana bambanta daga model zuwa model.</li>
</ul>
</div>

